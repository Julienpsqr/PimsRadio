export interface LiquidsoapConfig {
  icecastHost: string;
  icecastPort: number;
  icecastPassword: string;
  mount: string;
  /** Folder of last-resort tracks, always available. */
  fallbackDir: string;
  /** Port of the Liquidsoap telnet server (control plane link). */
  telnetPort: number;
  /** Port accepting a live feed from a studio (Icecast-source protocol). */
  harborPort: number;
  harborPassword: string;
  bitrateKbps: number;
}

/** Quote a value as a Liquidsoap string literal. */
export function lqString(v: string): string {
  if (/[\u0000-\u001f]/.test(v)) throw new Error("control characters not allowed in script values");
  return `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/**
 * Generate the engine script. Scripts are generated, never hand-edited (ADR 0001).
 * Source priority: live studio > control-plane queue > fallback folder, with
 * `mksafe` so the output can never go silent.
 *
 * NOTE: written for Liquidsoap 2.x; not yet validated against a running engine
 * (Docker is needed). Treat as a draft until the Phase 1 soak test.
 */
export function generateScript(c: LiquidsoapConfig): string {
  for (const [name, n] of Object.entries({
    icecastPort: c.icecastPort, telnetPort: c.telnetPort, harborPort: c.harborPort, bitrateKbps: c.bitrateKbps,
  })) {
    if (!Number.isInteger(n) || n <= 0 || n > 65535) throw new Error(`invalid ${name}`);
  }
  if (!c.mount.startsWith("/")) throw new Error("mount must start with /");
  return `# Generated by PimsRadio - do not edit by hand.
settings.server.telnet := true
settings.server.telnet.bind_addr := "0.0.0.0"
settings.server.telnet.port := ${c.telnetPort}

# 1) Tracks pushed by the control plane
queue = request.queue(id="auto")

# 2) Last-resort folder: always playable
emergency = mksafe(playlist(mode="randomize", reload_mode="watch", ${lqString(c.fallbackDir)}))

# 3) Live studio feed (highest priority)
live = input.harbor("live", port=${c.harborPort}, password=${lqString(c.harborPassword)})

radio = fallback(track_sensitive=false, [live, queue, emergency])
radio = mksafe(radio)
radio = normalize(radio)

output.icecast(
  %mp3(bitrate=${c.bitrateKbps}),
  host=${lqString(c.icecastHost)}, port=${c.icecastPort},
  password=${lqString(c.icecastPassword)}, mount=${lqString(c.mount)},
  radio
)
`;
}
